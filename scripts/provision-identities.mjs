#!/usr/bin/env node
/**
 * provision-identities.mjs — clean provisioning path for control-plane
 * catalog identities.
 *
 * The catalog only ingests entities from locations (files/URLs), so
 * "adding a user" means producing the right org-data file. This script is
 * that path: it takes a short list of GitHub usernames + group
 * memberships and renders the exact User/Group entity YAML the catalog
 * ingests, validating every input against the same constraints the
 * sign-in resolver and permission policy rely on:
 *
 *   - entity names must be lowercase GitHub logins (the production
 *     sign-in resolver `usernameMatchingUserEntityName` matches the
 *     GitHub profile's login against the entity name, so the entity name
 *     MUST be the exact lowercase login),
 *   - groups must be a known group (platform-team, platform-admins —
 *     see GROUPS below; platform-admins membership is what the
 *     permission policy reads for full access),
 *   - no duplicate users.
 *
 * Usage:
 *   node scripts/provision-identities.mjs \
 *     --input org.identities.json --output examples/org.provisioned.yaml
 *   node scripts/provision-identities.mjs \
 *     --users "alice:platform-team;bob:platform-team,platform-admins"
 *   node scripts/provision-identities.mjs \
 *     --check --output examples/org.provisioned.yaml   # CI guard
 *
 * Input JSON shape: {"users":[{"github":"alice","groups":["platform-team"]}]}
 * With no input the script renders a groups-only skeleton (nobody can
 * sign in and nobody is an admin until users are provisioned).
 *
 * See docs/identity-and-access.md "Provisioning users and admins".
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { parseArgs } from 'node:util';

/** The only groups the control plane recognizes. Adding a group here is a
 * deliberate policy decision (and must be mirrored in the catalog rules). */
const GROUPS = {
  'platform-team': {
    description:
      "Development/ops team for the App Factory control plane's own catalog " +
      'entities and the Platform MFE Application template.',
  },
  'platform-admins': {
    description:
      'Full-access group for the control plane permission policy - see ' +
      'packages/backend/src/permissions/policy.ts. Nobody is an admin until ' +
      'a User entity below adds spec.memberOf: [platform-admins].',
  },
};

// GitHub login rules (https://github.com/settings/username): 1-39 chars,
// lowercase alphanumerics and hyphens, must not start or end with a hyphen.
const USERNAME_RE = /^[a-z0-9](?:[a-z0-9-]{0,37}[a-z0-9])?$/;

function parseInlineUsers(spec) {
  // "alice:platform-team;bob:platform-team,platform-admins"
  const users = [];
  for (const chunk of spec.split(';')) {
    const trimmed = chunk.trim();
    if (!trimmed) continue;
    const [github, groupsPart = ''] = trimmed.split(':');
    users.push({
      github,
      groups: groupsPart
        .split(',')
        .map(g => g.trim())
        .filter(Boolean),
    });
  }
  return users;
}

function validateAndNormalize(users) {
  const seen = new Set();
  const out = [];
  for (const user of users) {
    const github = String(user.github ?? '').trim();
    if (!github) {
      throw new Error(`missing "github" username in ${JSON.stringify(user)}`);
    }
    if (github !== github.toLowerCase()) {
      throw new Error(
        `GitHub username must be lowercase so it matches the login the ` +
          `sign-in resolver receives: "${github}"`,
      );
    }
    if (!USERNAME_RE.test(github)) {
      throw new Error(
        `invalid GitHub username "${github}" (1-39 chars, lowercase ` +
          `alphanumerics and hyphens, no leading/trailing hyphen)`,
      );
    }
    if (seen.has(github)) {
      throw new Error(`duplicate GitHub username "${github}"`);
    }
    seen.add(github);

    const groups = [
      ...new Set(
        (user.groups ?? []).map(g => String(g).trim()).filter(Boolean),
      ),
    ];
    for (const group of groups) {
      if (!GROUPS[group]) {
        throw new Error(
          `unknown group "${group}" - allowed: ${Object.keys(GROUPS).join(', ')}`,
        );
      }
    }
    out.push({ github, groups });
  }
  return out;
}

function renderYaml(users) {
  const lines = [];
  lines.push(
    '# Generated by scripts/provision-identities.mjs - DO NOT EDIT BY HAND.',
  );
  lines.push(
    '# Regenerate: node scripts/provision-identities.mjs --input <org.json> --output examples/org.provisioned.yaml',
  );
  lines.push(
    '# See docs/identity-and-access.md "Provisioning users and admins".',
  );

  for (const groupName of Object.keys(GROUPS)) {
    lines.push('---');
    lines.push(
      '# https://backstage.io/docs/features/software-catalog/descriptor-format#kind-group',
    );
    lines.push('apiVersion: backstage.io/v1alpha1');
    lines.push('kind: Group');
    lines.push('metadata:');
    lines.push(`  name: ${groupName}`);
    lines.push('  description: >-');
    lines.push(`    ${GROUPS[groupName].description}`);
    lines.push('spec:');
    lines.push('  type: team');
    lines.push('  children: []');
  }

  for (const user of users) {
    lines.push('---');
    lines.push(
      '# https://backstage.io/docs/features/software-catalog/descriptor-format#kind-user',
    );
    lines.push('apiVersion: backstage.io/v1alpha1');
    lines.push('kind: User');
    lines.push('metadata:');
    lines.push(`  name: ${user.github}`);
    // Double-quoted: the description embeds the GitHub login, and a plain
    // scalar containing ": " (e.g. "GitHub login: alice") is rejected by
    // the catalog's strict YAML parser. Usernames are validated to never
    // contain `"`, so double quotes are safe here.
    lines.push(
      `  description: "Provisioned control-plane operator (GitHub login: ${user.github})"`,
    );
    lines.push('spec:');
    lines.push(`  memberOf: [${user.groups.join(', ')}]`);
  }

  lines.push('');
  return lines.join('\n');
}

function main() {
  const { values } = parseArgs({
    options: {
      input: { type: 'string' },
      users: { type: 'string' },
      output: { type: 'string', default: 'examples/org.provisioned.yaml' },
      check: { type: 'boolean', default: false },
    },
  });

  let rawUsers;
  if (values.input) {
    if (!existsSync(values.input)) {
      console.error(`--input file not found: ${values.input}`);
      process.exit(1);
    }
    const parsed = JSON.parse(readFileSync(values.input, 'utf8'));
    rawUsers = Array.isArray(parsed) ? parsed : parsed.users;
  } else if (values.users) {
    rawUsers = parseInlineUsers(values.users);
  } else {
    rawUsers = [];
  }

  let users;
  try {
    users = validateAndNormalize(rawUsers);
  } catch (err) {
    console.error(`provision-identities: ${err.message}`);
    process.exit(1);
  }

  const rendered = renderYaml(users);

  if (values.check) {
    if (!existsSync(values.output)) {
      console.error(`--check: ${values.output} does not exist`);
      process.exit(1);
    }
    const current = readFileSync(values.output, 'utf8');
    if (current !== rendered) {
      console.error(
        `--check: ${values.output} is out of date or tampered with - ` +
          `regenerate it with the same input.`,
      );
      process.exit(1);
    }
    console.log(
      `OK: ${values.output} matches provisioning input ` +
        `(${users.length} user(s), ${Object.keys(GROUPS).length} groups).`,
    );
    process.exit(0);
  }

  writeFileSync(values.output, rendered);
  console.log(
    `Wrote ${values.output}: ${users.length} user(s), ` +
      `${Object.keys(GROUPS).length} groups.`,
  );
}

main();
